#!/usr/bin/env python3
"""Generate examples/puzzle/Logo.swift from the 96x96 ASCII-art picture below (python3 tools/genlogo.py [output]).

The picture is cut into 12x12 tiles of 8x8 pixels. Identical tiles are stored only once, so the output is the
unique tiles (2bpp, 16 bytes each) plus a 12x12 map of indices into them.
Shades: ' ' = color 0 (lightest), '.' = color 1, '#' = color 2. Color 3 is left to the puzzle (frame and empty slot).

The picture is the Swift logo. Swift and the Swift logo are trademarks of Apple Inc.
"""
