def main():
    rows = [line.ljust(SIZE) for line in ART.split('\n')[:SIZE]]
    assert len(rows) == SIZE and all(len(r) == SIZE for r in rows)

    tiles, index, tile_map = [], {}, []
    for ty in range(SIZE // 8):
        for tx in range(SIZE // 8):
            data = []
            for y in range(8):
                lo = hi = 0
                for x in range(8):
                    shade = SHADES[rows[ty * 8 + y][tx * 8 + x]]
                    lo = lo << 1 | (shade & 1)
                    hi = hi << 1 | (shade >> 1)
                data += [lo, hi]
            key = bytes(data)
            if key not in index:
                index[key] = len(tiles)
                tiles.append(key)
            tile_map.append(index[key])
    assert len(tiles) <= 128, "too many unique tiles for tile numbers 0x80-0xFF"

    side = SIZE // 8
    out = []
    out.append("// Generated by tools/genlogo.py. Do not edit by hand.")
    out.append("//")
    out.append(f"// The Swift logo as a {SIZE}x{SIZE} picture: {len(tiles)} unique 8x8 tiles and a {side}x{side} tile map.")
    out.append("// Swift and the Swift logo are trademarks of Apple Inc.")
    out.append("")
    out.append("enum Logo {")
    out.append("  /// Width and height of the picture in tiles")
    out.append(f"  static let side = {side}")
    out.append(f"  static let tileCount = {len(tiles)}")
    out.append("")
    out.append("  /// 2bpp tile data (16 bytes per tile, one tile per line)")
    out.append("  static let tiles: [UInt8] = [")
    for t in tiles:
        out.append("    " + " ".join(f"0x{b:02X}," for b in t))
    out.append("  ]")
    out.append("")
    out.append(f"  /// Index into `tiles` for each cell of the picture ({side} per row)")
    out.append("  static let map: [UInt8] = [")
    for y in range(side):
        out.append("    " + " ".join(f"{v:3d}," for v in tile_map[y * side:(y + 1) * side]))
    out.append("  ]")
    out.append("}")
    text = "\n".join(out) + "\n"

    path = sys.argv[1] if len(sys.argv) > 1 else "examples/puzzle/Logo.swift"
    with open(path, "w") as f:
        f.write(text)
    print(f"{path}: {len(tiles)} unique tiles ({len(tiles) * 16} bytes) + {len(tile_map)} map bytes")


if __name__ == '__main__':
    main()
